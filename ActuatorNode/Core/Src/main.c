// CAN 메시지 수신 인터럽트 콜백
void HAL_CAN_RxFifo0MsgPendingCallback(CAN_HandleTypeDef *hcan) {
    if (HAL_CAN_GetRxMessage(hcan, CAN_RX_FIFO0, &rxHeader, rxData) == HAL_OK) {
        // 센서 보드에서 보낸 데이터 파싱 (예: 센서ID=rxData[0], 거리=rxData[1]<<8 | rxData[2])
        distance = (rxData[1] << 8) | rxData[2];

        // 거리별 동적 알람 처리
        update_alarm(distance);
    }
}

void update_alarm(uint16_t dist) {
    if (dist > 80) { // 80cm보다 멀면 끄기
        __HAL_TIM_SET_COMPARE(&htim1, TIM_CHANNEL_1, 0);
        __HAL_TIM_SET_COMPARE(&htim1, TIM_CHANNEL_2, 0);
    }
    else {
        // 거리가 가까울수록(dist 작을수록) ARR 값을 작게 설정하여 주기를 빠르게 함
        // 예: 80cm일 때 ARR=2000, 10cm일 때 ARR=500
        uint32_t new_arr = (dist * 20) + 300;
        __HAL_TIM_SET_AUTORELOAD(&htim1, new_arr);

        // Duty Cycle을 50%로 유지 (소리를 가장 크게 내는 비율)
        __HAL_TIM_SET_COMPARE(&htim1, TIM_CHANNEL_1, new_arr / 2);
        __HAL_TIM_SET_COMPARE(&htim1, TIM_CHANNEL_2, new_arr / 2);
    }
}
